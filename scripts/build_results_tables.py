"""Generate research/thesis/results/*.md from the tested qll functions. Run after any physics change:
python scripts/build_results_tables.py. Every number in the thesis results chapter comes from here."""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "thesis" / "results"


def fmt_s(s: float) -> str:
    return f"{s*1e3:.2f} ms" if s < 1 else f"{s:.1f} s" if s < 120 else f"{s/60:.1f} min" if s < 7200 else f"{s/3600:.2f} h"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    from qll.channels.fiber_loss import attenuation_length_km, transmittance
    from qll.channels.free_space_diffraction import geometric_transmittance
    from qll.channels.light_time_delay import one_way_delay_s, round_trip_delay_s
    from qll.channels.link_budget import JINAN1_2025, MICIUS_2017, slant_range_m
    from qll.circuits.noise.thermal import bose_einstein_occupation
    from qll.constants.astro import AU_METERS, EARTH_MARS_MAX_M, EARTH_MARS_MIN_M
    from qll.network.memory_decoherence import BASELINES, MEMORY_TABLE, capability_matrix, crossover_time_s
    from qll.network.purification import bbpssw_rounds_to_target
    from qll.network.repeater_chain import crossover_distance_km
    from qll.qkd.key_rate import bb84_qber_threshold
    from qll.qkd.plob_bound import plob_bits_per_use
    from qll.space.classical_link import DSOC_PSYCHE, ppm_data_rate_bps, received_photons_per_s
    from qll.space.conjunction import availability, blackout_windows
    from qll.space.ephemeris import SYNODIC_PERIOD_DAYS, range_envelope_m
    from qll.space.relay_constellation import Relay, constellation_availability
    from qll.app.messenger import required_buffer_bytes

    lines = ["# Results tables (generated)", "", "Generated by `scripts/build_results_tables.py` from the tested functions; do not edit by hand.", ""]

    # 1 thermal
    lines += ["## 1. Thermal occupation", "", "| Carrier | T | n̄ |", "|---|---|---|"]
    for f, T, name in ((5e9, 300.0, "5 GHz qubit, 300 K"), (5e9, 0.015, "5 GHz qubit, 15 mK"), (193.4e12, 300.0, "193 THz photon, 300 K")):
        lines.append(f"| {name} | {T} K | {bose_einstein_occupation(2*math.pi*f, T):.3g} |")

    # 2 channels
    lo, hi = range_envelope_m()
    lines += ["", "## 2. Channels and light time", "", "| Quantity | Value | Source |", "|---|---|---|",
              f"| Fiber attenuation length at 0.2 dB/km | {attenuation_length_km():.1f} km | `fiber_loss.py` |",
              f"| Fiber transmittance, 100 km | {transmittance(100):.3g} | |",
              f"| Free-space geometric η, 1200 km, 15 cm → 1 m, 810 nm | {geometric_transmittance(1.2e6, 810e-9, 0.15, 1.0):.3g} | `free_space_diffraction.py` |",
              f"| Free-space geometric η, Mars min, 15 cm → 10 m, 1550 nm | {geometric_transmittance(EARTH_MARS_MIN_M, 1550e-9, 0.15, 10.0):.3g} | |",
              f"| Earth–Mars range envelope (Kepler model) | {lo/AU_METERS:.4f}–{hi/AU_METERS:.4f} au | `space/ephemeris.py` |",
              f"| One-way light time, Mars min / max | {fmt_s(one_way_delay_s(EARTH_MARS_MIN_M))} / {fmt_s(one_way_delay_s(EARTH_MARS_MAX_M))} | `light_time_delay.py` |",
              f"| Round trip, Mars min / max | {fmt_s(round_trip_delay_s(EARTH_MARS_MIN_M))} / {fmt_s(round_trip_delay_s(EARTH_MARS_MAX_M))} | |",
              f"| Synodic period | {SYNODIC_PERIOD_DAYS:.1f} d | |"]

    # 3 link budgets
    lines += ["", "## 3. Satellite link budgets", "", "| Mission | Elevation | Range | Single-link loss | Two-link loss |", "|---|---|---|---|---|"]
    for name, lb in (("Micius 2017", MICIUS_2017), ("Jinan-1 2025", JINAN1_2025)):
        for el in (15, 30, 45, 90):
            L = slant_range_m(500e3, el); d = lb.loss_db(L, el)
            lines.append(f"| {name} | {el}° | {L/1e3:.0f} km | {d:.1f} dB | {2*d:.1f} dB |")
    lines.append("\nReported: Micius two-downlink loss 64–82 dB over a pass [yin2017].")

    # 4 QKD
    lines += ["", "## 4. Key rates", "", f"- BB84 QBER threshold: {bb84_qber_threshold()*100:.2f} %",
              f"- PLOB capacity at η = 10⁻³: {plob_bits_per_use(1e-3):.3g} bits/use; at 10⁻⁶: {plob_bits_per_use(1e-6):.3g}"]

    # 5 memories (REQ-CAP-001)
    cm = capability_matrix(0.95)
    lines += ["", "## 5. Memory capability matrix (REQ-CAP-001), f₀ = 0.95", "", "| Memory | Lifetime | Efficiency | Crossover (F = 2/3) | " + " | ".join(BASELINES) + " |", "|---|---|---|---|" + "---|" * len(BASELINES)]
    for p in MEMORY_TABLE:
        tc = crossover_time_s(0.95, p.lifetime_s, p.model)
        lines.append(f"| {p.name} | {fmt_s(p.lifetime_s)} | {p.efficiency:.1%} | {fmt_s(tc)} | " + " | ".join("✓" if cm[p.name][b] else "✗" for b in BASELINES) + " |")
    lines.append("\nBaselines (round trip): " + ", ".join(f"{b} {fmt_s(t)}" for b, t in BASELINES.items()))

    # 6 repeaters
    lines += ["", "## 6. Repeater chain crossover (REQ-NET-001)", "", "| Memory T₂ | Segments | Crossover distance |", "|---|---|---|"]
    for T2 in (1e-3, 1.0, 3600.0):
        for n in (3, 4):
            L = crossover_distance_km(n, T2)
            lines.append(f"| {fmt_s(T2)} | {2**n} | {'none' if L is None else f'{L:.0f} km'} |")
    r, F, pairs = bbpssw_rounds_to_target(0.8, 0.99)
    lines.append(f"\nBBPSSW from F = 0.80 to 0.99: {r} rounds, F = {F:.4f}, {pairs:.0f} input pairs per output pair; each round is one classical round trip ({fmt_s(round_trip_delay_s(EARTH_MARS_MAX_M))} at Mars max).")

    # 7 space
    t = np.arange(0.0, 20 * 365.25, 1.0)
    w = blackout_windows(t, 3.0)
    relays_direct = [Relay("E", "earth_orbit")]; relays_l4 = relays_direct + [Relay("L4", "L4"), Relay("L5", "L5")]
    t2 = np.arange(0.0, 2 * SYNODIC_PERIOD_DAYS, 3.0)
    lines += ["", "## 7. Space segment", "",
              f"- Solar conjunction blackouts (SEP < 3°) in 20 years: {len(w)}, mean length {np.mean([b-a for a,b in w]):.0f} d; direct availability {availability(t, 3.0):.1%}",
              f"- Availability with an Earth-orbit relay only: {constellation_availability(relays_direct, t2):.1%}; with L4 and L5 relays: {constellation_availability(relays_l4, t2):.2%}"]
    for L_au in (0.2, 1.0, 2.5):
        ph = received_photons_per_s(L_m=L_au * AU_METERS, **DSOC_PSYCHE)
        lines.append(f"- DSOC-class classical link at {L_au} au: {ph:.2e} photons/s → {ppm_data_rate_bps(ph)/1e6:.0f} Mb/s")

    # 8 messenger
    lines += ["", "## 8. Messenger (REQ-APP-001)", "", "| Distance | Round trip | Key buffer for 1 msg/min with zero key rate |", "|---|---|---|"]
    for d, n in ((3.844e8, "Moon"), (EARTH_MARS_MIN_M, "Mars min"), (EARTH_MARS_MAX_M, "Mars max")):
        lines.append(f"| {n} | {fmt_s(round_trip_delay_s(d))} | {required_buffer_bytes(0.0, d, 32, messages_per_s=1/60)/1e3:.2f} kB |")

    # 9 DI under latency (E10)
    from qll.qkd.e91 import di_rate_per_round, rounds_for_positive_di_key
    S = 2 * math.sqrt(2)
    lines += ["", "## 9. Device-independent certification under latency (E10, REQ-SEC-001)", "", "| Device S | Asymptotic rate | Rounds for positive key (ε = 1e-10) | Pair rate to gather them in one Mars-max round trip |", "|---|---|---|---|"]
    for frac in (1.0, 0.98, 0.95, 0.92):
        n = rounds_for_positive_di_key(S * frac, 0.01)
        lines.append(f"| {frac:.2f}·2√2 | {di_rate_per_round(S*frac, 0.01):.3f} | {n:,} | {n/round_trip_delay_s(EARTH_MARS_MAX_M):.2f} pairs/s |")

    # 10 transduction (E7)
    from qll.circuits.teleportation import analytic_average_fidelity
    from qll.hardware.transduction import OPTIMISTIC_2025, STATE_OF_THE_ART_2020, TARGET
    lines += ["", "## 10. Transduction trade (E7)", "", "| Transducer | η_t | n_add | Signal fraction | Teleportation fidelity through it | Entanglement survives |", "|---|---|---|---|---|---|"]
    for t in (STATE_OF_THE_ART_2020, OPTIMISTIC_2025, TARGET):
        f = max(0.95 * t.signal_fraction(), 0.25)
        lines.append(f"| {t.name.split(' [')[0]} | {t.efficiency:g} | {t.added_noise:g} | {t.signal_fraction():.2f} | {analytic_average_fidelity(f):.3f} | {'yes' if t.preserves_entanglement() else 'no'} |")
    lines.append(f"\nTransduction-free reference at the same source fraction 0.95: F = {analytic_average_fidelity(0.95):.3f}.")

    (OUT / "tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT/'tables.md'}")


if __name__ == "__main__":
    main()
